/**
 * CONDITION CARDS — structured, plain-language patient education.
 *
 * One card per condition: what it is, how it shows, how it is confirmed, how it
 * is treated, what the person can do, what makes it urgent, and what to ask.
 * A card says what is generally true; it never says what THIS patient has or
 * should take. Every card names the guideline it follows.
 *
 * STATUS: authored 2026-10-17, pending clinical review by the medical director
 * (listed in the clinical review document). Plain-language Georgian, no doses.
 */

