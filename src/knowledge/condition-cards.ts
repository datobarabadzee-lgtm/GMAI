/** Cards whose condition appears in the text, most specific first (earlier in the list wins ties). */
export function cardsFor(text: string, limit = 2): ConditionCard[] {
  return CONDITION_CARDS.filter((c) => c.re.test(text)).slice(0, limit);
}

/**
 * Whether the person writes as someone who HAS the condition ("მაქვს გაფანტული
 * სკლეროზი", "დამისვეს") or asks about it. Unclear → null, and both readings
 * are shown.
 */
export function livesWith(text: string, card: ConditionCard): boolean | null {
  const t = text.toLowerCase();
  const name = card.re.source;
  void name;
  if (/დამისვეს|დამიდგინეს|დადგენილი მაქვს|დიაგნოზით|მკურნალობას ვიტარებ|ვიღებ/.test(t)) return true;
  const m = card.re.exec(text);
  if (m) {
    const around = text.slice(Math.max(0, m.index - 25), m.index + m[0].length + 25);
    if (/მაქვს|მჭირს|ვარ\b/.test(around) && !/რას ნიშნავს|რა არის/.test(around)) return true;
  }
  return null;
}
