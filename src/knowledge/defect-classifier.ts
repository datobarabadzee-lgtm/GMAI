/** Heuristic classification of a free-text case narrative into candidate defect classes. */
export function suggestDefectClasses(text: string): { cls: DefectClass; hits: string[] }[] {
  const t = text.toLowerCase();
  return DEFECT_CLASSES.map((cls) => ({ cls, hits: cls.detectionSignals.filter((s) => t.includes(s.toLowerCase())) }))
    .filter((r) => r.hits.length > 0)
    .sort((a, b) => b.hits.length - a.hits.length);
}
