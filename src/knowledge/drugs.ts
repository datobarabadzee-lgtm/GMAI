export const drugById = (id: string): Drug | undefined => DRUGS.find((d) => d.id === id);

const normalize = (s: string) => s.toLowerCase().trim();

/**
 * Curated monograph for a SUBSTANCE name typed exactly (INN, Georgian INN or
 * registry id; a trailing dose such as "5 მგ" is ignored). Trade names and
 * fragments do not resolve here: a brand is a product, and product identity is
 * confirmed only through the medication identity service
 * (src/server/medications). See brandOnlyMatch for the brand case.
 */
export function findDrug(name: string): Drug | undefined {
  const n = substanceKey(name);
  if (!n) return undefined;
  return DRUGS.find((d) => normalize(d.generic_name) === n || normalize(d.generic_ka) === n || d.id === n || normalize(d.generic_name).split(' ')[0] === n && n.length >= 6);
}

/** The substance part of a medication line: text before the first digit. */
function substanceKey(name: string): string {
  return normalize(name.split(/\d/)[0] ?? '').replace(/[,.;:]+$/, '').trim();
}

/** A curated trade name, exactly — reported as "product selection required", never dosed. */
export function brandOnlyMatch(name: string): Drug | undefined {
  const n = substanceKey(name);
  if (!n) return undefined;
  return DRUGS.find((d) => d.brand_names.some((b) => normalize(b) === n));
}

export function searchDrugs(q: string): Drug[] {
  const n = normalize(q);
  if (!n) return DRUGS;
  return DRUGS.filter(
    (d) =>
      normalize(d.generic_name).includes(n) ||
      normalize(d.generic_ka).includes(n) ||
      normalize(d.class).includes(n) ||
      d.atc.toLowerCase().includes(n) ||
      d.brand_names.some((b) => normalize(b).includes(n)) ||
      d.indications.some((i) => normalize(i).includes(n)),
  );
}

export function interactionsFor(ids: string[]): Interaction[] {
  const set = new Set(ids);
  return INTERACTIONS.filter((i) => set.has(i.a) && set.has(i.b));
}
